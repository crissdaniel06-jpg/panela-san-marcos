-- Human-readable order lookup number; the UUID primary key remains unchanged.
begin;
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='orders' and column_name='public_number'
  ) then
    alter table public.orders
      add column public_number bigint generated by default as identity (start with 1001);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid='public.orders'::regclass and conname='orders_public_number_unique'
  ) then
    alter table public.orders
      add constraint orders_public_number_unique unique (public_number);
  end if;
end
$$;
comment on column public.orders.public_number is
  'Customer-facing order number. UUID id remains the internal primary key and FK target.';
commit;
